/**
 * Fetches https://decomp.dev/projects.json and writes src/data/decomp-dev-projects.js
 * with catalogue entries not already present in portProjects (matched by GitHub repo URL).
 *
 * Usage: npm run sync:decomp-dev
 * Run assign:decomp-twitch or edit decomp-dev-twitch-cache.json before sync for covers.
 */
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import {
  DECOMP_DEV,
  DECOMP_DEV_EXCLUDED_PLATFORMS,
  DECOMP_DEV_PLATFORM_LABELS,
  decompDevProjectUrl,
  isDecompDevExcludedRepo,
} from '../src/data/decomp-dev-source.js'
import { portProjects } from '../src/data/projects.js'
import { inferYearFromGameName, isDecompDevGame, loadMetadataCache } from './decomp-dev-metadata.mjs'
import { loadTwitchCache } from './decomp-dev-twitch-cache.mjs'

const OUT = fileURLToPath(new URL('../src/data/decomp-dev-projects.js', import.meta.url))
const APPROACH_DECOMP = 'Decompilation'

const normalizeRepo = (url) =>
  url?.replace(/\.git$/i, '').replace(/\/$/, '').toLowerCase() ?? ''

const slugify = (owner, repo) =>
  `${owner}-${repo}`
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')

const formatPercent = (value) => {
  if (value == null || Number.isNaN(value)) return null
  return `${value.toFixed(1).replace(/\.0$/, '')}%`
}

const buildSummary = (measures) => {
  const matched = formatPercent(measures?.matched_code_percent)
  const linked = formatPercent(measures?.complete_code_percent)
  if (matched && linked) {
    return `Matching decompilation tracked on decomp.dev (${matched} matched code, ${linked} fully linked).`
  }
  if (matched) {
    return `Matching decompilation tracked on decomp.dev (${matched} matched code).`
  }
  return 'Matching decompilation tracked on decomp.dev.'
}

const response = await fetch(DECOMP_DEV.projectsFeedUrl, {
  headers: { 'User-Agent': 'native-oldies/1.0 (decomp.dev sync)' },
})
if (!response.ok) {
  throw new Error(`decomp.dev feed responded ${response.status}`)
}

const { projects: remoteProjects } = await response.json()
if (!Array.isArray(remoteProjects)) {
  throw new Error('decomp.dev feed: expected { projects: [] }')
}

const existingRepos = new Set(
  portProjects.map((project) => normalizeRepo(project.repo)).filter(Boolean),
)

const usedIds = new Set(portProjects.map((project) => project.id))
const metadataCache = await loadMetadataCache()
const twitchCache = await loadTwitchCache()
const entries = []
let skippedNonGame = 0
let skippedWindows = 0
let skippedExcludedRepo = 0

for (const remote of remoteProjects) {
  const repoUrl = remote.repo_url?.trim()
  if (!repoUrl || existingRepos.has(normalizeRepo(repoUrl))) continue

  const owner = remote.owner
  const repo = remote.repo
  if (!owner || !repo) continue

  const gameName = remote.name ?? `${owner}/${repo}`
  if (!isDecompDevGame(gameName, repo)) {
    skippedNonGame += 1
    continue
  }

  if (remote.platform && DECOMP_DEV_EXCLUDED_PLATFORMS.has(remote.platform)) {
    skippedWindows += 1
    continue
  }

  if (isDecompDevExcludedRepo(owner, repo)) {
    skippedExcludedRepo += 1
    continue
  }

  let id = slugify(owner, repo)
  if (usedIds.has(id)) {
    id = `${id}-decomp`
  }
  if (usedIds.has(id)) continue
  usedIds.add(id)

  const platform = DECOMP_DEV_PLATFORM_LABELS[remote.platform] ?? remote.platform ?? 'Unknown'
  const progressUrl = decompDevProjectUrl(owner, repo)

  /** @type {import('../src/data/projects.js').Project} */
  const entry = {
    id,
    game: gameName,
    project: repo,
    platform,
    approach: APPROACH_DECOMP,
    year: 0,
    summary: buildSummary(remote.measures),
    repo: repoUrl,
    website: progressUrl,
    catalogSource: 'decomp.dev',
    status: 'wip',
  }

  const cached = metadataCache[`${owner}/${repo}`]
  const inferredYear = inferYearFromGameName(gameName)
  entry.year = cached?.year ?? inferredYear ?? 0

  const twitch = twitchCache[`${owner}/${repo}`]
  if (twitch?.twitchBoxArtId) entry.twitchBoxArtId = twitch.twitchBoxArtId
  if (twitch?.twitchCoverUrl) entry.twitchCoverUrl = twitch.twitchCoverUrl

  entries.push(entry)
}

entries.sort((a, b) => a.game.localeCompare(b.game, 'en'))

const fileBody = `/**
 * AUTO-GENERATED by scripts/sync-decomp-dev-projects.mjs — do not edit by hand.
 * Source: ${DECOMP_DEV.catalogUrl} (${DECOMP_DEV.projectsFeedUrl})
 * Generated: ${new Date().toISOString()}
 * Entries: ${entries.length} (skipped ${skippedNonGame} non-game, ${skippedWindows} Windows, ${skippedExcludedRepo} excluded repos)
 */
import { DECOMP_DEV } from './decomp-dev-source.js'

export { DECOMP_DEV }

/** @typedef {import('./projects.js').Project} Project */

/** @type {Project[]} */
export const decompDevProjects = ${JSON.stringify(entries, null, 2)}
`

await writeFile(OUT, fileBody)
console.log(
  `Wrote ${entries.length} decomp.dev games to ${OUT} (skipped ${skippedNonGame} non-game, ${skippedWindows} Windows, ${skippedExcludedRepo} excluded repos)`,
)
